function Topics({ topics }: { topics: Topic[] }) {
  return (
    <div className="help">
      {topics.map((topic) => (
        <section key={topic.title} className="help-topic">
          <h2>{topic.title}</h2>
          <ol>{topic.steps.map((step) => <li key={step}>{step}</li>)}</ol>
        </section>
      ))}
    </div>
  );
}

const titles = { resident: 'Как пользоваться', company: 'Как работает пульт', platform: 'Как работает платформа' } as const;

// A person sees help only for the roles they have: a resident is not shown
// how the company desk works.
export function HelpScreen({ initialRole }: { initialRole?: 'resident' | 'company' | 'platform' }) {
  const { mode } = useSession();
  // Help for the current mode only: as a resident, the desk is not shown.
  const allowed = (mode === 'platform' ? ['platform', 'company'] : mode === 'company' ? ['company'] : ['resident']) as ReadonlyArray<'resident' | 'company' | 'platform'>;
  const start = initialRole && allowed.includes(initialRole) ? initialRole : allowed[0]!;
  const [role, setRole] = useState<'resident' | 'company' | 'platform'>(start);
  const labels = { resident: 'Жителю', company: 'Сотруднику УК', platform: 'Админу' } as const;
  return (
    <Page title={titles[role]}>
      {allowed.length > 1 ? <Segmented items={allowed.map((id) => ({ id, title: labels[id] }))} activeItem={role} onClick={(id) => setRole(id as typeof role)} /> : null}
      <Topics topics={role === 'resident' ? resident : role === 'company' ? [...company, desktop] : platform} />
    </Page>
  );
}
